#!/usr/bin/env node
// Turn tzdata's zone.tab into the place the Day / Night page offers as a first
// guess at where the camera is.
//
// The sun needs a latitude and a longitude, and a camera on plain HTTP cannot
// ask the browser for one: navigator.geolocation is refused outside a secure
// context. What the camera does know is the time zone it was given on the Time
// page, and zone.tab gives each zone the coordinates of the city it is named
// after. That is a guess, often hundreds of kilometres out -- Asia/Kolkata
// covers all of India -- which is why the page offers it and never saves it.
// Hundreds of kilometres move dusk by minutes, not hours, so as a guess it is
// worth having.
//
// Usage: node tools/harvest-tz-places.js [zone.tab] > www/a/tz-places.js
// zone.tab defaults to /usr/share/zoneinfo/zone.tab.
//
// Names are keyed with spaces where tzdata has underscores, the spelling
// timezone.js and therefore /etc/timezone use ("America/New York"); the
// lookup in sun-place.js normalises both sides anyway.

'use strict';

const fs = require('fs');

const src = process.argv[2] || '/usr/share/zoneinfo/zone.tab';
const out = {};
// ISO 6709: +DDMM+DDDMM or +DDMMSS+DDDMMSS.
function dms(s, degDigits) {
	const sign = s[0] === '-' ? -1 : 1;
	const body = s.slice(1);
	const d = +body.slice(0, degDigits);
	const m = +body.slice(degDigits, degDigits + 2);
	const sec = body.length > degDigits + 2 ? +body.slice(degDigits + 2, degDigits + 4) : 0;
	return sign * Math.round((d + m / 60 + sec / 3600) * 100) / 100;
}
fs.readFileSync(src, 'utf8').split('\n').forEach((line) => {
	if (!line || line[0] === '#') return;
	const f = line.split('\t');
	const m = /^([+-]\d+)([+-]\d+)$/.exec(f[1] || '');
	if (!m || !f[2]) return;
	out[f[2].replace(/_/g, ' ')] = [dms(m[1], 2), dms(m[2], 3)];
});

const keys = Object.keys(out).sort();
process.stdout.write(
	'// GENERATED by tools/harvest-tz-places.js from tzdata zone.tab -- do not edit\n' +
	'// by hand. The city each time zone is named after, as [latitude, longitude]:\n' +
	'// a first guess at where a camera is, offered by the Day / Night page and\n' +
	'// never saved without the owner choosing it.\n' +
	'(function () {\n' +
	'\tconst TZ_PLACES = {\n' +
	keys.map((k) => '\t\t' + JSON.stringify(k) + ': [' + out[k][0] + ', ' + out[k][1] + '],').join('\n') +
	'\n\t};\n' +
	"\tif (typeof module === 'object' && module.exports) module.exports = TZ_PLACES;\n" +
	"\tif (typeof window === 'object') window.MajesticTzPlaces = TZ_PLACES;\n" +
	'})();\n');
